#!/usr/bin/env python3
"""Site lookout layout: the mulcher among the site trees and the walking
paths beside the tree rows, added to the flat tree world (trees.py).

Mulcher at MULCHER (map frame), facing the nearest tree, with the lookout
experiment's mulcher model and roof lidar (lookout/build_world.py).
Paths: straight lanes parallel to the ROI's long axis, one on each side of
the tree band, at the ROI-frame offset v whose clearance to every trunk is at
least LANE_CLEAR (3 m lane half-width 1.5 m + oak root flare 1.7 m); they run
EXTEND m past both ends of the ROI. Each is drawn as a flat, visual-only strip.

Writes <world dir>/site_layout.sdf, layout.yaml, layout.png.
Usage: layout.py <world dir>
"""
import csv, math, os, sys
import numpy as np
import matplotlib; matplotlib.use('Agg')
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, '..', 'lookout'))
from build_site_world import ROI_ORIGIN, ROI_THETA, ROI_SIZE
import build_world as lk

MULCHER = (-2.0, 0.6)
LANE_HALF = 1.5
LANE_CLEAR = 3.2
EXTEND = 20.0
C, S = math.cos(math.radians(ROI_THETA)), math.sin(math.radians(ROI_THETA))


def to_uv(x, y):
    dx, dy = x - ROI_ORIGIN[0], y - ROI_ORIGIN[1]
    return C * dx + S * dy, -S * dx + C * dy


def to_xy(u, v):
    return ROI_ORIGIN[0] + C * u - S * v, ROI_ORIGIN[1] + S * u + C * v


def lane_clearance(v, T):
    us = np.linspace(-EXTEND, ROI_SIZE[0] + EXTEND, 561)
    return min(np.hypot(tu - us, tv - v).min() for tu, tv in T)


def strip(name, a, b):
    (x0, y0), (x1, y1) = a, b
    L = math.hypot(x1 - x0, y1 - y0); yaw = math.atan2(y1 - y0, x1 - x0)
    return (f'    <model name="{name}"><static>true</static><pose>{(x0 + x1) / 2:.2f} {(y0 + y1) / 2:.2f} 0.005 0 0 {yaw:.4f}</pose>'
            f'<link name="l"><visual name="v"><geometry><box><size>{L:.2f} {2 * LANE_HALF} 0.01</size></box></geometry>'
            f'<material><ambient>0.45 0.35 0.22 1</ambient><diffuse>0.55 0.43 0.28 1</diffuse></material></visual></link></model>\n')


def main():
    wdir = sys.argv[1]
    trees = list(csv.DictReader(open(f'{wdir}/trees.csv')))
    T = [to_uv(float(t['x']), float(t['y'])) for t in trees]
    # south lane: the highest v below the band with enough clearance; north: the lowest above it
    vs = np.arange(-10, ROI_SIZE[1] + 10.01, 0.25)
    ok = [v for v in vs if lane_clearance(v, T) >= LANE_CLEAR]
    v_s = max(v for v in ok if v < ROI_SIZE[1] / 2); v_n = min(v for v in ok if v > ROI_SIZE[1] / 2)
    paths = []
    for pid, v in (('S', v_s), ('N', v_n)):
        a, b = to_xy(-EXTEND, v), to_xy(ROI_SIZE[0] + EXTEND, v)
        paths.append(dict(id=pid, v=float(v), polyline=[list(np.round(a, 3)), list(np.round(b, 3))],
                          clearance=round(float(lane_clearance(v, T)), 2)))
    mu, mv = to_uv(*MULCHER)
    near = min(trees, key=lambda t: math.hypot(float(t['x']) - MULCHER[0], float(t['y']) - MULCHER[1]))
    yaw = math.atan2(float(near['y']) - MULCHER[1], float(near['x']) - MULCHER[0])
    for p in paths:
        p['mulcher_dist'] = round(abs(p['v'] - mv), 2)
    w = open(f'{wdir}/trees.sdf').read().replace('<world name="site_trees">', '<world name="site_layout">')
    extra = lk.mulcher_model(lk.husky_lidar_block(), MULCHER[0], MULCHER[1], round(yaw, 4))
    extra += ''.join(strip(f'path_{p["id"]}', *p['polyline']) for p in paths)
    open(f'{wdir}/site_layout.sdf', 'w').write(w.replace('</world>', extra + '\n</world>'))
    with open(f'{wdir}/layout.yaml', 'w') as f:
        f.write(f'# Generated by site_lookout/layout.py\nworld: site_layout\nmulcher: {{x: {MULCHER[0]}, y: {MULCHER[1]}, yaw: {yaw:.4f}, facing: {near["name"]}}}\n'
                f'lane_half: {LANE_HALF}\nlane_clear: {LANE_CLEAR}\npaths:\n')
        for p in paths:
            f.write(f'  - {{id: {p["id"]}, roi_v: {p["v"]}, clearance: {p["clearance"]}, mulcher_dist: {p["mulcher_dist"]}, polyline: {p["polyline"]}}}\n')
    print('mulcher yaw', round(math.degrees(yaw), 1), 'facing', near['name'])
    for p in paths:
        print(p['id'], 'roi v', p['v'], 'clearance', p['clearance'], 'm; distance to mulcher', p['mulcher_dist'], 'm')
    figure(f'{wdir}/layout.png', trees, paths, yaw)


def figure(path, trees, paths, yaw):
    fig, ax = plt.subplots(figsize=(15, 7))
    corn = [to_xy(u, v) for u, v in ((0, 0), (ROI_SIZE[0], 0), ROI_SIZE, (0, ROI_SIZE[1]), (0, 0))]
    ax.plot(*zip(*corn), 'r-', lw=0.8, label='ROI')
    for t in trees:
        col = 'tab:orange' if t['type'] == 'oak' else 'tab:green'
        ax.add_patch(plt.Circle((float(t['x']), float(t['y'])), float(t['crown_r_m']), color=col, alpha=0.35))
        ax.plot(float(t['x']), float(t['y']), '.', color=col, ms=4)
    for p in paths:
        (x0, y0), (x1, y1) = p['polyline']
        ax.plot([x0, x1], [y0, y1], color='saddlebrown', lw=4, alpha=0.6)
        ax.text(x1, y1, f' path {p["id"]} ({p["mulcher_dist"]:.1f} m from mulcher)', va='center', fontsize=9)
    ax.plot(*MULCHER, 's', color='darkorange', mec='k', ms=10, label='mulcher')
    ax.annotate('', xy=(MULCHER[0] + 3 * math.cos(yaw), MULCHER[1] + 3 * math.sin(yaw)), xytext=MULCHER,
                arrowprops=dict(arrowstyle='->', lw=1.5))
    ax.plot([], [], 'o', color='tab:orange', alpha=0.5, label='oak (crown)')
    ax.plot([], [], 'o', color='tab:green', alpha=0.5, label='pine (crown)')
    ax.set_aspect('equal'); ax.legend(loc='upper left'); ax.set_xlabel('x (m)'); ax.set_ylabel('y (m)')
    ax.set_title('Site layout: mulcher at (-2, 0.6), paths beside the tree rows')
    fig.tight_layout(); fig.savefig(path, dpi=110)


if __name__ == '__main__':
    main()
